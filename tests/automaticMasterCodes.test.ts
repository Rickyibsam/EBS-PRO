import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const migration = await readFile(new URL("../supabase/migrations/20261107064125_auto_generate_master_entry_codes.sql", import.meta.url), "utf8");
const extension = await readFile(new URL("../supabase/migrations/20261107064206_auto_generate_additional_master_codes.sql", import.meta.url), "utf8");
const securityMigration = await readFile(new URL("../supabase/migrations/20261107064324_deny_client_access_to_master_code_sequences.sql", import.meta.url), "utf8");
const branchMigration = await readFile(new URL("../supabase/migrations/20261107064450_fix_branch_warehouse_auto_code.sql", import.meta.url), "utf8");
const integration = await readFile(new URL("../supabase/tests/auto_generated_master_codes.sql", import.meta.url), "utf8");
const workspace = await readFile(new URL("../src/WorkspaceModule.tsx", import.meta.url), "utf8");
const admin = await readFile(new URL("../src/AdminModule.tsx", import.meta.url), "utf8");
const hr = await readFile(new URL("../src/HRModule.tsx", import.meta.url), "utf8");
const assets = await readFile(new URL("../src/AssetBudgetModule.tsx", import.meta.url), "utf8");
const invite = await readFile(new URL("../supabase/functions/invite-tenant-member/index.ts", import.meta.url), "utf8");

test("new product, customer and supplier codes are generated by database triggers", () => {
  assert.match(migration, /before insert on public\.products/i);
  assert.match(migration, /before insert on public\.parties/i);
  assert.match(migration, /SKU-/);
  assert.match(migration, /CUS-/);
  assert.match(migration, /SUP-/);
  assert.match(migration, /on conflict \(tenant_id, entity_type\)/i);
});

test("master code sequence is tenant-isolated and inaccessible to client roles", () => {
  assert.match(migration, /primary key \(tenant_id, entity_type\)/i);
  assert.match(migration, /enable row level security/i);
  assert.match(migration, /revoke all on table public\.master_code_sequences from public, anon, authenticated/i);
  assert.match(migration, /security definer/i);
  assert.match(migration, /set search_path = pg_catalog, public/i);
  assert.match(securityMigration, /for all\s+to public\s+using \(false\)\s+with check \(false\)/i);
});

test("master entry forms no longer require manual codes", () => {
  assert.match(workspace, /sku:editingProductId\?productForm\.sku\.trim\(\):""/);
  assert.match(workspace, /Auto-generated on save/);
  assert.doesNotMatch(workspace, /SKU and product name are required/);
  assert.match(admin, /employee_code:""/);
  assert.match(admin, /route_code:""/);
  assert.match(admin, /code:""/);
  assert.match(hr, /code:"",name:departmentName\.trim\(\)/);
  assert.match(hr, /code:"",name:designationName\.trim\(\)/);
  assert.match(assets, /Auto-generated on save/);
});

test("staff invitation delegates employee code assignment to the database", () => {
  assert.match(invite, /fullName\.length < 2 \|\| !branchId/);
  assert.match(invite, /employee_code: ""/);
  assert.doesNotMatch(invite, /employee code is already in use/i);
});

test("additional master tables receive tenant-scoped automatic identifiers", () => {
  for (const table of ["warehouses", "departments", "designations", "employees", "fixed_assets", "sales_routes"]) {
    assert.ok(extension.toLowerCase().includes("before insert on public." + table));
  }
  for (const prefix of ["WH-", "DEP-", "DSG-", "EMP-", "AST-", "RTE-"]) {
    assert.ok(extension.includes(prefix));
    assert.ok(integration.includes(prefix));
  }
});

test("branch bootstrap uses generated warehouse codes rather than a tenant-global constant", () => {
  assert.match(branchMigration, /values\(new\.tenant_id,new\.id,'Main Warehouse','',true\)/i);
  assert.match(integration, /Branch bootstrap warehouse code failed/);
});

test("database acceptance test verifies generated codes and preserves legacy codes inside rollback", () => {
  assert.match(integration.trimStart(), /^--[\s\S]*?begin;/);
  assert.match(integration, /SKU-\[0-9\]\{6\}/);
  assert.match(integration, /CUS-\[0-9\]\{6\}/);
  assert.match(integration, /SUP-\[0-9\]\{6\}/);
  assert.match(integration, /LEGACY-CODE-KEEP/);
  assert.match(integration.trimEnd(), /rollback;$/i);
  assert.doesNotMatch(integration, /\bcommit\s*;/i);
});
